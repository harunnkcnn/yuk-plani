export const dictionaries: Record<Lang, Dict> = { tr, en };

export function detectLang(): Lang {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function formatters(lang: Lang) {
  const locale = lang === 'tr' ? 'tr-TR' : 'en-US';
  const int = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
  const dec1 = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 });
  const dec2 = new Intl.NumberFormat(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  return {
    int: (n: number) => int.format(n),
    m1: (mm: number) => dec1.format(mm / 1000),
    m2: (mm: number) => dec2.format(mm / 1000),
    dec2: (n: number) => dec2.format(n),
    pct: (n: number) => int.format(Math.round(n * 100)),
  };
}
